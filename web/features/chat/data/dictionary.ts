const TRIM_PUNCT = /^[^a-zA-Z0-9]+|[^a-zA-Z0-9]+$/g;

export function lookupWord(rawToken: string): WordLookupResult | null {
  const cleaned = rawToken.replace(TRIM_PUNCT, "");
  if (!cleaned || !/[a-zA-Z]/.test(cleaned)) return null;
  const lower = cleaned.toLowerCase();

  if (DICTIONARY[lower]) {
    return { word: cleaned, key: lower, ...DICTIONARY[lower] };
  }

  for (const suffix of ["nya", "kan", "lah", "kah", "i"]) {
    if (lower.endsWith(suffix) && lower.length > suffix.length + 2) {
      const stem = lower.slice(0, -suffix.length);
      if (DICTIONARY[stem]) {
        return { word: cleaned, key: stem, ...DICTIONARY[stem] };
      }
    }
  }

  if (lower.includes("-")) {
    const firstPart = lower.split("-")[0];
    if (DICTIONARY[firstPart]) {
      return { word: cleaned, key: firstPart, ...DICTIONARY[firstPart] };
    }
  }

  return null;
}

export interface TextSegment {
  text: string;
  lookup: WordLookupResult | null;
}

export function tokenizeText(text: string): TextSegment[] {
  const parts = text.split(/(\s+)/);
  const segments: TextSegment[] = [];

  for (const part of parts) {
    if (!part) continue;
    if (/^\s+$/.test(part)) {
      segments.push({ text: part, lookup: null });
      continue;
    }
    const leadMatch = part.match(/^[^a-zA-Z0-9]+/);
    const trailMatch = part.match(/[^a-zA-Z0-9]+$/);
    const lead = leadMatch ? leadMatch[0] : "";
    const trail = trailMatch && (!leadMatch || trailMatch.index! > 0) ? trailMatch[0] : "";
    const core = part.slice(lead.length, part.length - trail.length);

    if (!core) {
      segments.push({ text: part, lookup: null });
      continue;
    }

    if (lead) segments.push({ text: lead, lookup: null });
    segments.push({ text: core, lookup: lookupWord(core) });
    if (trail) segments.push({ text: trail, lookup: null });
  }

  return segments;
}
